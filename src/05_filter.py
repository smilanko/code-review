"""Step 5: quality filters on the deduplicated records (the length filter comes after the tokenizer).

Methods
  parse errors   drop methods tree-sitter could not parse cleanly (e.g. `String @Nullable... xs`):
                 removing annotations from a broken parse can delete code
  generated      drop methods from generated files (path, header marker, known generator, @Generated)
  non-English    drop non-English Javadoc; drop non-English inline comments (code is kept)
  stale Javadoc  drop the Javadoc when an @param names a parameter the method does not have, or it
                 has @return on a void method (code is kept); a Javadoc that only omits some
                 parameters is incomplete, not wrong, and is kept
  trivial        drop getters, setters, fluent setters, empty bodies and one-call delegations that
                 have no Javadoc left
Commit messages
  AI-assisted    drop commits marked as written with an AI assistant (flag set in 04_dedup.py)
  bots           drop commits by bot authors
  revert/merge   drop "Revert ..." and "Merge branch/pull request ..." messages
  non-English    drop non-English messages
Review threads
  bots           remove comments by bots (incl. AI reviewers); drop threads with no human comment left
  per-hunk cap   at most MAX_THREADS_PER_HUNK threads on the same diff hunk (earliest kept); runs after
                 the bot filter so that bot threads do not take the slots
  non-English    drop threads with non-English comments

Non-English = at least 2 letters from a non-Latin script (CJK, Cyrillic, Arabic, ...), after removing
code spans and URLs. No trained language model is used.

Output: $DATA/filtered/{methods,commits,reviews}.jsonl.gz, $DATA/filtered/examples.json (5 removed
examples per filter) and corpus/counts/05_filter.json.

Usage: python src/05_filter.py
"""
import gzip
import json
import os
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = Path(os.environ.get("DATA", ROOT.parent / "data.nosync"))   # .nosync: keep iCloud out of it
IN, OUT = DATA / "dedup", DATA / "filtered"
MAX_THREADS_PER_HUNK = 10

# --- non-English --------------------------------------------------------------------------------
# code spans, URLs and Javadoc tags are removed before checking the language
CODEISH = re.compile(r"```.*?```|`[^`]*`|https?://\S+|\{@\w+[^}]*\}", re.S)


# Non-English = at least 2 letters from outside the Latin alphabets (code point above 0x24F:
# Chinese, Cyrillic, Arabic, ...), counted after code spans and URLs are removed. Real examples:
#     "更新README内容"            -> non-English (Chinese letters)
#     "Fix NPE in `getItem()`"   -> English
# Latin-script languages (German, Spanish) are not detected; a stopword guesser misjudged short
# English, so we chose this simpler, predictable rule.
def non_english(text):
    return sum(1 for c in CODEISH.sub(" ", text) if c.isalpha() and ord(c) > 0x24F) >= 2


# --- generated code -----------------------------------------------------------------------------
GEN_PATH = re.compile(r"(^|/)(generated|gen-src|generated-sources)/|\.pb\.java$|Grpc\.java$|OuterClass\.java$")
IDE_STUB = re.compile(r"auto-?generated (javadoc|method stub|catch block|constructor stub)", re.I)
GEN_HEADER = re.compile(r"\b(auto-?generated|automatically generated|generated (by|from|with|using)"
                        r"|this (file|class) (is|was) generated|do not (edit|modify))\b", re.I)
GEN_TOOL = re.compile(r"MyBatis Generator|@mbg\.generated|BNF Converter|BNFC|OpenAPI Generator|openapi-generator"
                      r"|Swagger Codegen|swagger-codegen|protocol buffer compiler|Generated by the protocol"
                      r"|by ANTLR|Generated By:JavaCC|by jOOQ|GENERATED CODE|Code generated by|AutoRest", re.I)
GEN_ANNOTATION = re.compile(r"^\s*@(javax\.annotation\.(processing\.)?|jakarta\.annotation\.)?Generated\b(?!Value)", re.M)
CODE_START = re.compile(r"^\s*(package|import|public|class|final|abstract|@)", re.M)


# Is this file generated by a tool rather than written by a person? True if any of:
#   - its path:   .../generated/..., *.pb.java (protobuf), ...Grpc.java
#   - its header (the comment before the code): "auto-generated", "do not edit", ...
#   - a known generator's signature anywhere: MyBatis Generator, OpenAPI Generator, ANTLR, jOOQ, ...
#   - a @Generated annotation (but not JPA's @GeneratedValue, which marks a database id)
# IDE template comments ("Auto-generated method stub") do not count: a person wrote the rest.
# Checked once per file and cached, since a file holds many methods.
def generated_file(repo, path, _cache={}):
    key = (repo, path)
    if key not in _cache:
        src = (DATA / "clones" / repo.replace("/", "__") / path).read_text(encoding="utf-8", errors="replace")
        # the header is the text before the code starts; IDE template comments do not count
        m = CODE_START.search(src)
        header = IDE_STUB.sub("", src[:m.start()] if m else src[:2000])
        _cache[key] = bool(GEN_PATH.search(path) or GEN_HEADER.search(header) or GEN_TOOL.search(src)
                           or GEN_ANNOTATION.search(src))
    return _cache[key]


# --- stale Javadoc and trivial methods ----------------------------------------------------------
PARAM_TAG = re.compile(r"@param\s+<?(\w+)>?")


# A stale Javadoc no longer matches its code: the code changed and the doc did not. Stale if
#   - an @param names a parameter the method does not have, e.g.
#         @param values the array to encode ...     on a method with no parameter `values`
#   - or it has @return on a void method.
# Such a doc would teach the model a wrong code-English link, so the doc is removed (the code stays).
# A doc that merely omits some parameters is incomplete, not wrong, and is kept.
def stale_javadoc(m):
    doc = m["javadoc"]
    tagged = set(PARAM_TAG.findall(doc))
    generic = {t for t in tagged if re.fullmatch(r"[A-Z]\w*", t)}   # @param <T> type parameters
    if (tagged - generic) - set(m["params"]):
        return True
    return m["void"] and "@return" in doc


# Method bodies too simple to teach anything on their own. Real examples removed:
#     AsyncSsePublisherImpl(AsyncHandle asyncHandle) { this.asyncHandle = asyncHandle; }      (setter)
#     public CompletionStage<?> send(String message) { return send(message, null, null); }    (delegation)
# They are dropped only when they have no Javadoc; with one, the English makes them worth keeping.
TRIVIAL = [re.compile(p) for p in (
    r"^$",                                                  # empty body
    r"^return (this\.)?\w+;$",                              # getter
    r"^(this\.)?\w+ = \w+;$",                               # setter
    r"^(this\.)?\w+ = \w+; return this;$",                  # fluent setter
    r"^(return )?(super|this)?\.?\w+\([\w, ]*\);$",         # one-call delegation
)]


def trivial(code):
    body = code[code.find("{") + 1:code.rfind("}")].strip()
    return any(p.match(body) for p in TRIVIAL)


BLOCK_COMMENT = re.compile(r"/\*.*?\*/")

# --- bots, revert/merge ---------------------------------------------------------------------------
# Bots write templated text, not how people describe changes. Real examples removed:
#     commit by dependabot[bot]: "Bump junit from 4.13 to 4.13.1 ..."
#     review by a code-analysis bot: "*MissingOverride:* ... expected @Override"
# Reverts and merges only repeat another commit's message plus a hash:
#     "Revert "Fixed Javadoc" This reverts commit aae1185..."
BOT = re.compile(r"\[bot\]|-bot\b|\bbot$|dependabot|renovate|github-actions|greenkeeper|snyk|mergify"
                 r"|allcontributors|imgbot|codecov|sonarcloud|coderabbit|copilot|cursor|gemini-code-assist"
                 r"|sourcery|deepsource|weblate|crowdin|transifex|semantic-release|release-please", re.I)
REVERT_MERGE = re.compile(r"^(revert \"|merge (branch|pull request|remote-tracking))", re.I)


# counts every removal per rule and keeps 5 examples; rules starting with ~ modify instead of remove
class Log:
    def __init__(self):
        self.counts, self.examples = defaultdict(Counter), defaultdict(list)

    def __call__(self, source, rule, example):
        self.counts[source][rule] += 1
        if len(self.examples[f"{source}/{rule}"]) < 5:
            self.examples[f"{source}/{rule}"].append(example[:400])


def filter_methods(recs, log):
    for m in recs:
        # each rule either drops the method (continue) or edits it and moves on
        if m["has_error"]:
            log("methods", "parse errors", m["code"]); continue
        if generated_file(m["repo"], m["path"]):
            log("methods", "generated", m["code"]); continue
        if m["javadoc"] and non_english(m["javadoc"]):
            log("methods", "~javadoc non-English (doc removed)", m["javadoc"]); m["javadoc"] = ""
        # remove only the non-English /* */ comments; keep the code
        if any(non_english(c) for c in m["comments"]):
            log("methods", "~comments non-English (comments removed)", m["code_c"])
            m["code_c"] = BLOCK_COMMENT.sub(lambda x: "" if non_english(x.group(0)) else x.group(0), m["code_c"])
            m["code_c"] = " ".join(m["code_c"].split())
            m["comments"] = [c for c in m["comments"] if not non_english(c)]
        if m["javadoc"] and stale_javadoc(m):
            log("methods", "~javadoc stale (doc removed)", m["javadoc"] + "  ||  " + m["code"]); m["javadoc"] = ""
        # runs last, so a method whose Javadoc was just removed is judged without it
        if not m["javadoc"] and trivial(m["code"]):
            log("methods", "trivial without Javadoc", m["code"]); continue
        yield m


def filter_commits(recs, log):
    for c in recs:
        if c["ai"]:
            log("commits", "AI-assisted", c["text"]); continue
        if BOT.search(c["author"] + " " + c["email"]):
            log("commits", "bots", c["author"] + ": " + c["text"]); continue
        if REVERT_MERGE.match(c["text"]):
            log("commits", "revert/merge", c["text"]); continue
        if non_english(c["text"]):
            log("commits", "non-English", c["text"]); continue
        yield c


def filter_reviews(recs, log):
    per_hunk = Counter()
    for r in sorted(recs, key=lambda r: r["id"]):            # GitHub ids increase with time: earliest first
        # keep human comments; a thread with none left is dropped
        human = [c for c in r["comments"] if c["user_type"] != "Bot" and not BOT.search(c["user"] or "")]
        if not human:
            log("reviews", "bots (whole thread)", r["comments"][0]["body"]); continue
        if len(human) < len(r["comments"]):
            log("reviews", "~bots (bot replies removed)", r["comments"][0]["body"])
            r["comments"] = human
        # at most MAX_THREADS_PER_HUNK threads on the same code block (earliest kept)
        hunk = " ".join(r["diff_hunk"].split())
        per_hunk[hunk] += 1
        if per_hunk[hunk] > MAX_THREADS_PER_HUNK:
            log("reviews", "per-hunk cap", r["comments"][0]["body"]); continue
        if any(non_english(c["body"]) for c in r["comments"]):
            log("reviews", "non-English", r["comments"][0]["body"]); continue
        yield r


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    log, summary = Log(), {}
    for source, fn in (("methods", filter_methods), ("commits", filter_commits), ("reviews", filter_reviews)):
        recs = [json.loads(l) for l in gzip.open(IN / f"{source}.jsonl.gz", "rt", encoding="utf-8")]
        n_in, n_out = len(recs), 0
        with gzip.open(OUT / f"{source}.jsonl.gz", "wt", encoding="utf-8") as f:
            for r in fn(recs, log):
                f.write(json.dumps(r, ensure_ascii=False) + "\n"); n_out += 1
        # split the log into removals and modifications; removals must add up
        removed = {k: v for k, v in log.counts[source].items() if not k.startswith("~")}
        modified = {k[1:]: v for k, v in log.counts[source].items() if k.startswith("~")}
        assert n_in - sum(removed.values()) == n_out, (source, n_in, removed, n_out)
        summary[source] = {"in": n_in, "removed": removed, "modified (kept)": modified, "out": n_out}
        print(source, json.dumps(summary[source], indent=1), flush=True)
    (OUT / "examples.json").write_text(json.dumps(log.examples, indent=1, ensure_ascii=False))
    (ROOT / "corpus/counts/05_filter.json").write_text(json.dumps(summary, indent=2) + "\n")


if __name__ == "__main__":
    main()
