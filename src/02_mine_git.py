"""Step 2: clone every repository of the frame and extract raw material from git.

For each repository in corpus/repos_ghs.csv:
  * blobless clone of the default branch (full history of commits, file contents only at HEAD);
  * the HEAD commit SHA is recorded: that is the snapshot we mine;
  * every Java method/constructor with a body is parsed with tree-sitter and stored as
      code     the method without comments and annotations, whitespace collapsed to single spaces
               (the format of the fine-tuning inputs)
      code_c   the same, with inline comments kept; `// x` becomes `/* x */` so that its end stays
               visible once line breaks are collapsed
      comments the text of those inline comments
      javadoc  the Javadoc immediately preceding the method, markers stripped, or ""
      params, void   parameter names and whether the return type is void (for the stale-Javadoc check)
  * every non-merge commit message on the default branch (full history, most recent first).

Nothing is filtered here except what cannot be parsed; filtering happens in 04_dedup.py and
05_filter.py so that every removal is counted. Output: $DATA/raw/<owner>__<name>.jsonl.gz and
corpus/repos.csv.

--pin rebuilds our snapshot: each repository is checked out at the SHA recorded in corpus/repos.csv
(instead of its latest commit), so methods and commit history are the ones we mined on 2026-10-12.

Resumable: a repository whose output exists is skipped; a clone is renamed into place only when
complete, so an interrupted run can simply be restarted.

Usage: python src/02_mine_git.py [--workers 16] [--limit N] [--pin]
"""
import argparse
import csv
import gzip
import json
import os
import re
import subprocess
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = Path(os.environ.get("DATA", ROOT.parent / "data.nosync"))   # .nosync: keep iCloud out of it
CLONES, RAW = DATA / "clones", DATA / "raw"
MAX_FILE_BYTES = 1_000_000          # larger .java files are almost always generated
CLONE_TIMEOUT = 1800
GEN_MARKERS = re.compile(r"auto-?generated|generated by|do not edit|@generated|javax\.annotation\.(processing\.)?Generated",
                         re.IGNORECASE)

_parser = None


def parser():
    global _parser
    if _parser is None:
        import tree_sitter_java
        from tree_sitter import Language, Parser
        _parser = Parser(Language(tree_sitter_java.language()))
    return _parser


def git(args, cwd=None, timeout=600):
    env = {**os.environ, "GIT_TERMINAL_PROMPT": "0", "GIT_LFS_SKIP_SMUDGE": "1"}
    return subprocess.run(["git", *args], cwd=cwd, env=env, timeout=timeout, check=True,
                          capture_output=True).stdout


def collapse(s):
    return " ".join(s.split())


def clean_javadoc(raw):
    body = raw[3:-2] if raw.endswith("*/") else raw[3:]
    lines = [re.sub(r"^\s*\*( |$)?", "", ln) for ln in body.splitlines()]
    return collapse("\n".join(lines))


def line_to_block(text):
    body = text[2:].strip().replace(b"*/", b"* /")
    return b"/* " + body + b" */" if body else b""


def render(src, node, drop, convert=False):
    """Source of `node` with descendants of type in `drop` removed; with `convert`, line comments
    are rewritten as block comments."""
    cuts, stack = [], [node]
    while stack:
        n = stack.pop()
        if n is not node and n.type in drop:
            cuts.append((n.start_byte, n.end_byte, b" "))
            continue
        if n is not node and convert and n.type == "line_comment":
            cuts.append((n.start_byte, n.end_byte, b" " + line_to_block(n.text) + b" "))
            continue
        stack.extend(n.children)
    out, pos = [], node.start_byte
    for a, b, repl in sorted(cuts):
        if a < pos:
            continue
        out.append(src[pos:a]); out.append(repl)
        pos = b
    out.append(src[pos:node.end_byte])
    return collapse(b"".join(out).decode("utf-8", "replace"))


COMMENTS = {"line_comment", "block_comment"}
ANNOTATIONS = {"marker_annotation", "annotation"}


def methods_of(src):
    tree = parser().parse(src)
    stack = [tree.root_node]
    while stack:
        n = stack.pop()
        stack.extend(n.children)
        if n.type not in ("method_declaration", "constructor_declaration"):
            continue
        if n.child_by_field_name("body") is None:   # abstract / interface methods
            continue
        prev = n.prev_named_sibling
        doc = ""
        if prev is not None and prev.type == "block_comment" and prev.text.startswith(b"/**"):
            doc = clean_javadoc(prev.text.decode("utf-8", "replace"))
        comments, cstack = [], [n]
        while cstack:
            c = cstack.pop()
            if c.type in COMMENTS:
                t = c.text.decode("utf-8", "replace")
                comments.append((c.start_byte, collapse(t[2:] if c.type == "line_comment" else t[2:-2])))
            else:
                cstack.extend(c.children)
        params = n.child_by_field_name("parameters")
        names = []
        if params is not None:
            for prm in params.named_children:
                ident = prm.child_by_field_name("name")
                if ident is None:   # varargs: spread_parameter > variable_declarator > identifier
                    ident = next((d.child_by_field_name("name") for d in prm.named_children
                                  if d.type == "variable_declarator"), None)
                if ident is not None:
                    names.append(ident.text.decode("utf-8", "replace"))
        rtype = n.child_by_field_name("type")
        yield {
            "code": render(src, n, COMMENTS | ANNOTATIONS),
            "code_c": render(src, n, ANNOTATIONS, convert=True),
            "comments": [t for _, t in sorted(comments) if t],
            "javadoc": doc,
            "params": names,
            "void": rtype is not None and rtype.type == "void_type",
            "line": n.start_point[0] + 1,
            "has_error": n.has_error,
        }


def mine(row, pin=None):
    """pin: (branch, sha) from corpus/repos.csv to check out, or None for the latest commit."""
    name = row["name"]
    slug = name.replace("/", "__")
    out = RAW / f"{slug}.jsonl.gz"
    meta = {"name": name, "branch": row["defaultBranch"], "sha": "", "status": "", "java_files": 0,
            "methods": 0, "commits": 0}
    if out.exists() and (RAW / f"{slug}.meta.json").exists():
        return json.loads((RAW / f"{slug}.meta.json").read_text())
    dest = CLONES / slug
    try:
        if not dest.exists():
            partial = CLONES / f"{slug}.partial"
            subprocess.run(["rm", "-rf", str(partial)], check=True)
            git(["clone", "--quiet", "--filter=blob:none", "--single-branch", "--no-tags",
                 f"https://github.com/{name}.git", str(partial)], timeout=CLONE_TIMEOUT)
            partial.rename(dest)
        if pin:
            branch, sha = pin
            try:
                git(["checkout", "--quiet", "--detach", sha], cwd=dest)
            except subprocess.CalledProcessError:       # not on the cloned branch any more: fetch it
                git(["fetch", "--quiet", "--filter=blob:none", "origin", sha], cwd=dest, timeout=CLONE_TIMEOUT)
                git(["checkout", "--quiet", "--detach", sha], cwd=dest)
        meta["sha"] = git(["rev-parse", "HEAD"], cwd=dest).decode().strip()
        meta["branch"] = pin[0] if pin else git(["rev-parse", "--abbrev-ref", "HEAD"], cwd=dest).decode().strip()
        tmp = out.with_suffix(".tmp")
        with gzip.open(tmp, "wt", encoding="utf-8") as f:
            files = git(["ls-files", "-z", "--", "*.java"], cwd=dest).split(b"\0")
            for rel in filter(None, files):
                p = dest / rel.decode("utf-8", "replace")
                if not p.is_file() or p.stat().st_size > MAX_FILE_BYTES:
                    continue
                src = p.read_bytes()
                meta["java_files"] += 1
                gen = bool(GEN_MARKERS.search(src[:3000].decode("utf-8", "replace")))
                for m in methods_of(src):
                    m.update(kind="method", repo=name, path=str(p.relative_to(dest)), generated=gen)
                    f.write(json.dumps(m, ensure_ascii=False) + "\n")
                    meta["methods"] += 1
            log = git(["log", "--no-merges", "--format=%H%x1f%an%x1f%ae%x1f%B%x1e"], cwd=dest)
            for rec in log.decode("utf-8", "replace").split("\x1e"):
                parts = rec.strip("\n").split("\x1f")
                if len(parts) != 4:
                    continue
                h, author, email, body = parts
                f.write(json.dumps({"kind": "commit", "repo": name, "commit": h, "author": author,
                                    "email": email, "text": body.strip()}, ensure_ascii=False) + "\n")
                meta["commits"] += 1
        tmp.rename(out)
        meta["status"] = "ok"
    except subprocess.TimeoutExpired:
        meta["status"] = "timeout"
    except subprocess.CalledProcessError as e:
        meta["status"] = "git-error: " + e.stderr.decode(errors="replace").strip().splitlines()[-1][:200]
    (RAW / f"{slug}.meta.json").write_text(json.dumps(meta))
    return meta


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=16)
    ap.add_argument("--limit", type=int)
    ap.add_argument("--pin", action="store_true", help="check out the SHAs in corpus/repos.csv")
    args = ap.parse_args()
    CLONES.mkdir(parents=True, exist_ok=True); RAW.mkdir(parents=True, exist_ok=True)
    rows = list(csv.DictReader(open(ROOT / "corpus/repos_ghs.csv")))[:args.limit]
    pins = {}
    if args.pin:
        pins = {r["name"]: (r["branch"], r["sha"]) for r in csv.DictReader(open(ROOT / "corpus/repos.csv")) if r["sha"]}
        missing = [r["name"] for r in rows if r["name"] not in pins]
        assert not missing, f"no recorded SHA for: {missing}"
    metas = []
    with ProcessPoolExecutor(args.workers) as ex:
        futs = {ex.submit(mine, r, pins.get(r["name"])): r["name"] for r in rows}
        for i, fut in enumerate(as_completed(futs), 1):
            m = fut.result(); metas.append(m)
            print(f"[{i}/{len(rows)}] {m['name']}: {m['status']} methods={m['methods']} commits={m['commits']}", flush=True)
    fields = ["name", "branch", "sha", "status", "java_files", "methods", "commits"]
    with open(ROOT / "corpus/repos.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, quoting=csv.QUOTE_ALL)
        w.writeheader()
        w.writerows(sorted(metas, key=lambda m: m["name"].lower()))
    ok = [m for m in metas if m["status"] == "ok"]
    print(f"ok {len(ok)}/{len(metas)}; methods {sum(m['methods'] for m in ok)}; commits {sum(m['commits'] for m in ok)}")


if __name__ == "__main__":
    main()
